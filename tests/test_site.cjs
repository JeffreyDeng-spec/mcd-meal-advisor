'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const demo=require('../site/app.js');
const base={mode:'demo',generated_at:'2026-10-19T12:00:00+08:00',plans:[{quoted_at:'2026-10-19T12:00:00+08:00',expires_at:'2026-10-19T12:15:00+08:00',coupon_comparison_expires_at:null,coupon_expiry:null}]};
const now=Date.parse('2027-01-01T12:00:00+08:00');
const reset=demo.resetClock(base,now);
assert.equal(Date.parse(reset.plans[0].quoted_at),now);
assert.equal(Date.parse(reset.plans[0].expires_at)-now,15*60000);
assert.equal(base.generated_at,'2026-10-19T12:00:00+08:00');
assert.throws(()=>demo.resetClock({...base,mode:'live'},now),/synthetic/);
assert.equal(demo.parseBudget('0.29'),29);
for(const x of ['NaN','Infinity','1.001','-1','1001','<script>'])assert.throws(()=>demo.parseBudget(x));
const text=demo.requestText(3000,true,'fries');
assert.ok(text.includes('30.00'));assert.ok(text.includes('薯条'));assert.ok(text.includes('选择真实营业门店'));
assert.ok(!text.includes('100001')&&!text.includes('SYNTHETIC'));
const burger={name:'汉堡',quantity:1},corn={name:'小份玉米杯',quantity:1},fries={name:'小份薯条',quantity:1};
const first={items:[burger,corn],payable_cents:2000,id:'a'},second={items:[burger,fries],payable_cents:2500,id:'b'};
assert.equal(demo.revisionTarget([first,second],first,'fries'),second);
assert.equal(demo.revisionTarget([first],first,'fries'),null);
const context={document:{getElementById(){return null;}}};vm.createContext(context);
vm.runInContext(fs.readFileSync('skills/mcd-meal-advisor/assets/report.js','utf8'),context);
assert.equal(typeof context.MealReport.pickPlans,'function');
console.log('Public demo: synthetic-only clock reset, budget validation, safe request copy, revision identity and engine embedding passed.');
